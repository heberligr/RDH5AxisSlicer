/**
 * Machine G-code generation (milestone 5).
 *
 * For each segment, in print order:
 *   - transition: retract, back the nozzle off along the tool axis, go up to
 *     safe Z, turn A/C, move above the segment's first point, come down,
 *     unretract. Rotary axes ONLY move here.
 *   - print: every move is plain X Y Z E (no A/C words). Points are the
 *     sliced toolpaths mapped part frame -> machine XYZ with the segment's pose.
 * Extrusion is relative (M83): E depends only on the length of each move, so
 * it doesn't change when the table is tilted.
 * Every output position is checked against the axis limits; any violation
 * stops generation with a clear message.
 */

import { withinLimits } from './config.js';
import { outsideLinearLimits, partToMachine, toCommanded } from './kinematics.js';
import { toPartFrame } from './slicer.js';

export class GcodeLimitError extends Error {}

const f3 = (x) => (Math.abs(x) < 5e-4 ? 0 : x).toFixed(3);
const f5 = (x) => x.toFixed(5);

/** Machine-frame point of every toolpath point of a sliced segment. */
function machinePoint(sliced, pivot, x, y, z) {
  return partToMachine(toPartFrame(sliced, x, y, z), sliced.pose, pivot);
}

/**
 * Build the G-code text.
 * @param {object[]} slicedSegments output of sliceAll(), in print order
 * @param {object} machine
 * @param {object} settings
 * @returns {{ text: string, stats: object, path: object[] }}
 *   path: the nozzle's route as {type, segmentId, layer, machine: [x,y,z], pose}
 *   entries (used by the collision checker and the animation).
 */
export function generateGcode(slicedSegments, machine, settings) {
  const s = settings.slicing;
  const mo = machine.motion;
  const k = machine.kinematics;
  const pivot = k.pivot;
  const filamentArea = Math.PI * (s.filament_diameter / 2) ** 2;
  const ePerMm = (s.line_width * s.layer_height) / filamentArea; // mm of filament per mm of line
  const travelF = s.travel_speed * 60;
  const out = [];
  const path = [];
  const errors = [];
  const stats = { segments: slicedSegments.length, layers: 0, extrudeMm: 0, travelMm: 0, filamentMm: 0, timeS: 0, rotations: 0 };

  let pos = null;          // current machine XYZ (null = unknown, after start block)
  let pose = { a: 0, c: 0 };
  let retracted = false;
  let where = 'start';     // for error messages

  const check = (p) => {
    if (outsideLinearLimits(p, machine)) {
      const L = machine.limits;
      errors.push(`${where}: X${f3(p[0])} Y${f3(p[1])} Z${f3(p[2])} is outside the limits X[${L.x}] Y[${L.y}] Z[${L.z}]`);
    }
  };
  const moveTo = (p, cmd, feed, extra = '') => {
    check(p);
    if (pos) {
      const dist = Math.hypot(p[0] - pos[0], p[1] - pos[1], p[2] - pos[2]);
      stats.timeS += dist / (feed / 60);
      if (cmd === 'G0') stats.travelMm += dist;
    }
    out.push(`${cmd} X${f3(p[0])} Y${f3(p[1])} Z${f3(p[2])}${extra} F${Math.round(feed)}`);
    pos = p;
  };
  const retract = () => {
    if (retracted || mo.retract_length <= 0) return;
    out.push(`G1 E-${f5(mo.retract_length)} F${Math.round(mo.retract_feedrate)}`);
    retracted = true;
  };
  const unretract = () => {
    if (!retracted) return;
    out.push(`G1 E${f5(mo.retract_length)} F${Math.round(mo.retract_feedrate)}`);
    retracted = false;
  };

  out.push('; Generated by RDH5AxisSlicer (3+2 segmented slicing)');
  out.push(`; machine: ${machine.name} (${machine.firmware}), pivot [${pivot.join(', ')}]`);
  out.push(`; layer ${s.layer_height} mm, line ${s.line_width} mm, ${s.perimeters} perimeters, infill ${Math.round(s.infill_density * 100)}%`);
  out.push(`; segments in print order: ${slicedSegments.map((x) => x.segmentId).join(', ')}`);
  out.push(...machine.start_gcode.trimEnd().split('\n'));
  out.push('G90 ; absolute XYZ and rotary', 'M83 ; relative extrusion');

  for (const sliced of slicedSegments) {
    const id = sliced.segmentId;
    const cmd = toCommanded(sliced.pose, machine);
    const firstPath = sliced.layers.flatMap((L) => L.paths.map((p) => ({ L, p })))[0];
    if (!firstPath) continue;
    const [fx, fy] = firstPath.p.points[0];
    const first = machinePoint(sliced, pivot, fx, fy, firstPath.L.z);

    // ---------------- transition ----------------
    where = `transition to segment ${id}`;
    out.push('', `; ===== SEGMENT ${id}: ${k.a_axis.letter}${f3(cmd.a)} ${k.c_axis.letter}${f3(cmd.c)} =====`);
    if (!withinLimits(k.a_axis, cmd.a) || !withinLimits(k.c_axis, cmd.c))
      errors.push(`${where}: ${k.a_axis.letter}${f3(cmd.a)} ${k.c_axis.letter}${f3(cmd.c)} is outside the rotary limits`);
    retract();
    if (pos) {
      const away = [pos[0], pos[1], Math.min(pos[2] + mo.safe_retract_distance, machine.limits.z[1])];
      out.push('; back off along the tool axis');
      moveTo(away, 'G0', travelF);
      path.push({ type: 'lift', segmentId: id, machine: away, pose });
    }
    const safe = [pos ? pos[0] : first[0], pos ? pos[1] : first[1], mo.safe_z];
    out.push('; up to safe Z');
    moveTo(safe, 'G0', travelF);
    path.push({ type: 'safe', segmentId: id, machine: safe, pose });
    const rotation = Math.max(Math.abs(sliced.pose.a - pose.a), Math.abs(sliced.pose.c - pose.c));
    out.push(`G0 ${k.a_axis.letter}${f3(cmd.a)} ${k.c_axis.letter}${f3(cmd.c)} F${Math.round(mo.rotary_feedrate)} ; rotate table`);
    stats.timeS += rotation / (mo.rotary_feedrate / 60);
    stats.rotations++;
    path.push({ type: 'rotate', segmentId: id, from: pose, to: sliced.pose, machine: safe });
    pose = sliced.pose;
    moveTo([first[0], first[1], mo.safe_z], 'G0', travelF);
    const above = [first[0], first[1], first[2] + mo.safe_retract_distance];
    moveTo(above, 'G0', travelF);
    path.push({ type: 'descend', segmentId: id, machine: above, pose });
    moveTo(first, 'G0', travelF);
    unretract();

    // ---------------- print ----------------
    for (const L of sliced.layers) {
      where = `segment ${id} layer ${L.index + 1}`;
      out.push(`;LAYER:${L.index} SEGMENT:${id}`);
      stats.layers++;
      const speed = (L.index === 0 ? s.first_layer_speed : s.print_speed) * 60;
      for (const p of L.paths) {
        const pts = p.points.map(([x, y]) => machinePoint(sliced, pivot, x, y, L.z));
        // Travel to the start of this path.
        const gap = Math.hypot(pts[0][0] - pos[0], pts[0][1] - pos[1], pts[0][2] - pos[2]);
        if (gap > 1e-6) {
          if (gap > s.retract_min_travel) retract();
          moveTo(pts[0], 'G0', travelF);
          unretract();
        }
        out.push(`;TYPE:${p.kind}`);
        for (let i = 1; i < pts.length; i++) {
          const len = Math.hypot(pts[i][0] - pos[0], pts[i][1] - pos[1], pts[i][2] - pos[2]);
          if (len < 1e-6) continue;
          const e = len * ePerMm;
          stats.extrudeMm += len;
          stats.filamentMm += e;
          moveTo(pts[i], 'G1', speed, ` E${f5(e)}`);
        }
        path.push({ type: 'print', segmentId: id, layer: L.index, machine: pos, pose });
      }
    }
  }

  where = 'end';
  retract();
  out.push('', ...machine.end_gcode.trimEnd().split('\n'), '');
  if (errors.length)
    throw new GcodeLimitError(
      `G-code would leave the machine's travel limits (${errors.length} problem${errors.length > 1 ? 's' : ''}):\n` +
        errors.slice(0, 5).join('\n') + (errors.length > 5 ? `\n... and ${errors.length - 5} more` : '') +
        '\nCheck kinematics.pivot, table.surface_z and limits in machine.yaml.',
    );
  stats.lines = out.length;
  return { text: out.join('\n'), stats, path };
}
